from public.activadores l
join (
  select distinct lider_id, lower(unaccent(btrim(coalesce(plaza_base, plaza)))) plaza_normalizada
  from public.activadores
  where rol = 'activador' and lider_id is not null
    and nullif(btrim(coalesce(plaza_base, plaza)), '') is not null
