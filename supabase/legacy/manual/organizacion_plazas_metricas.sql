  if to_regclass('public.activadores') is null or to_regclass('public.activaciones') is null then
    raise exception 'Preflight: deben existir public.activadores y public.activaciones';
  end if;
  if not exists (
    select 1 from information_schema.columns
    where table_schema = 'public' and table_name = 'activadores' and column_name = 'usuario_id' and udt_name = 'uuid'
  ) or not exists (
    select 1 from information_schema.columns
    where table_schema = 'public' and table_name = 'activaciones' and column_name = 'usuario_id' and udt_name = 'uuid'
  ) then
    raise exception 'Preflight: activadores.usuario_id y activaciones.usuario_id deben ser uuid';
