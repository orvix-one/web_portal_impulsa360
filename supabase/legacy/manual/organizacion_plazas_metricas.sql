  ) then
    raise exception 'Preflight: activaciones.es_plaza_temporal debe ser boolean';
  end if;
  foreach v_column in array array['nombre','rol','estado','lider_id','plaza'] loop
    if not exists (select 1 from information_schema.columns where table_schema = 'public' and table_name = 'activadores' and column_name = v_column) then
