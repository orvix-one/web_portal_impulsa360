  if not exists (
    select 1 from information_schema.columns
    where table_schema = 'public' and table_name = 'activadores' and column_name = 'lider_id' and udt_name = 'uuid'
  ) then
    raise exception 'Preflight: activadores.lider_id debe ser uuid';
